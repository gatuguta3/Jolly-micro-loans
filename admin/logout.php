<?php
session_start();

/* ---------- CLEAR "REMEMBER ME" COOKIE (if used) ---------- */
if (isset($_COOKIE['remember_token'])) {
    setcookie('remember_token', '', [
        'expires'  => time() - 3600,
        'path'     => '/',
        'secure'   => !empty($_SERVER['HTTPS']),
        'httponly' => true,
        'samesite' => 'Lax',
    ]);
    unset($_COOKIE['remember_token']);
}

/* ---------- DESTROY SESSION ---------- */
$_SESSION = [];

if (ini_get("session.use_cookies")) {
    $params = session_get_cookie_params();
    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );
}

session_destroy();

/* ---------- REDIRECT TO LOGIN ---------- */
header("Location: login.php");
exit;